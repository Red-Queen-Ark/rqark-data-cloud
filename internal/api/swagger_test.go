// serveSpec answers one request against a router carrying only the
// specification routes: they need no database, which is what lets this package
// test what it serves at all.
func serveSpec(t *testing.T, path string) map[string]any {
	t.Helper()

	gin.SetMode(gin.TestMode)
	router := gin.New()
	SwaggerRouter(router)

	recorder := httptest.NewRecorder()
	router.ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, path, nil))
	if recorder.Code != http.StatusOK {
		t.Fatalf("GET %s = %d, want 200", path, recorder.Code)
	}

	var document map[string]any
	if err := json.Unmarshal(recorder.Body.Bytes(), &document); err != nil {
		t.Fatalf("GET %s did not answer JSON: %v", path, err)
	}
	return document
}

// TestServedSpecDoesNotPinItsOwnAddress covers the host the generator writes
// when no @host annotation is set. Every deployment answers on its own address
// and port, so a document that names one of them is wrong for all the others.
func TestServedSpecDoesNotPinItsOwnAddress(t *testing.T) {
	document := serveSpec(t, "/api/swagger.json")

	for _, key := range []string{"host", "schemes"} {
		if value, present := document[key]; present {
			t.Errorf("the served document carries %q = %v, want the key absent", key, value)
		}
	}

	// The rest of the document is meant to survive the normalisation.
	if _, present := document["paths"]; !present {
		t.Fatal("the served document has no paths")
	}
	if document["basePath"] != "/api" {
		t.Errorf("basePath = %v, want /api", document["basePath"])
	}
}

// TestServedSpecCarriesNoInternalRoute covers the separation the claim and
// finalize endpoints depend on: they are guarded by a shared secret rather than
// by a user, so they are published nowhere. swag walks internal/api, and the
// internal package sits inside it, so only the generator's exclude keeps them
// out; this asserts the exclude is still doing its job.
func TestServedSpecCarriesNoInternalRoute(t *testing.T) {
	document := serveSpec(t, "/api/swagger.json")

	paths, ok := document["paths"].(map[string]any)
	if !ok {
		t.Fatal("the served document has no paths")
	}
	for path := range paths {
		if strings.Contains(path, "internal") {
			t.Errorf("the served document carries %q, want the internal routes left out", path)
		}
	}

	// The public task routes, which sit next to them, must still be there.
	if _, present := paths["/tasks"]; !present {
		t.Error("the served document lost the public task routes")
	}
}

// TestServedSpecIsTheOneInTheRepository covers the two artifacts drifting apart:
// the document the service answers with is generated by `go generate ./...` into
// docs/, and a regeneration that is committed in one place only leaves the other
// describing an API that no longer exists.
func TestServedSpecIsTheOneInTheRepository(t *testing.T) {
	onDisk, err := os.ReadFile(filepath.Join("..", "..", "docs", "swagger.json"))
	if err != nil {
		t.Fatalf("cannot read the generated document: %v", err)
	}

	var want map[string]any
	if err := json.Unmarshal(onDisk, &want); err != nil {
		t.Fatalf("the generated document is not valid JSON: %v", err)
	}

	got := serveSpec(t, "/api/swagger.json")
	if !reflect.DeepEqual(got, want) {
		t.Error("the served document differs from docs/swagger.json; run `go generate ./...` and commit it")
	}
}

// TestServedYAMLMatchesServedJSON covers the two renderings of the one parsed
// spec: a client that reads the YAML must not be told something else.
func TestServedYAMLMatchesServedJSON(t *testing.T) {
	gin.SetMode(gin.TestMode)
	router := gin.New()
	SwaggerRouter(router)

	recorder := httptest.NewRecorder()
	router.ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, "/api/swagger.yml", nil))
	if recorder.Code != http.StatusOK {
		t.Fatalf("GET /api/swagger.yml = %d, want 200", recorder.Code)
	}

	var fromYAML map[string]any
	if err := yaml.Unmarshal(recorder.Body.Bytes(), &fromYAML); err != nil {
		t.Fatalf("GET /api/swagger.yml did not answer YAML: %v", err)
	}

	for _, key := range []string{"host", "schemes"} {
		if value, present := fromYAML[key]; present {
			t.Errorf("the served YAML carries %q = %v, want the key absent", key, value)
		}
	}

	// The renderings are compared through YAML, which both of them marshal into,
	// and only on the part that says what the API is.
	fromJSON := serveSpec(t, "/api/swagger.json")
	gotPaths, err := yaml.Marshal(fromYAML["paths"])
	if err != nil {
		t.Fatalf("cannot re-encode the YAML paths: %v", err)
	}
	wantPaths, err := yaml.Marshal(fromJSON["paths"])
	if err != nil {
		t.Fatalf("cannot re-encode the JSON paths: %v", err)
	}
	if string(gotPaths) != string(wantPaths) {
		t.Error("the served YAML and the served JSON describe different paths")
	}
}

// TestDropUnservedSpecFieldsKeepsWhatIsSet covers the other half of the rule: a
// host or a scheme the annotations do state is a deliberate choice, and the
// normalisation must not take it away.
func TestDropUnservedSpecFieldsKeepsWhatIsSet(t *testing.T) {
	document := map[string]any{
		"host":     "api.example.com",
		"schemes":  []any{"https"},
		"basePath": "/api",
	}

	dropEmptyAddressFields(document)

	if document["host"] != "api.example.com" {
		t.Errorf("host = %v, want it kept", document["host"])
	}
	if !reflect.DeepEqual(document["schemes"], []any{"https"}) {
		t.Errorf("schemes = %v, want them kept", document["schemes"])
	}
}

// TestDropUnservedSpecFieldsRemovesTheEmptyOnes covers the two shapes the
// generator emits for an annotation nobody wrote.
func TestDropUnservedSpecFieldsRemovesTheEmptyOnes(t *testing.T) {
	document := map[string]any{
		"host":     "",
		"schemes":  []any{},
		"basePath": "/api",
	}

	dropEmptyAddressFields(document)

	for _, key := range []string{"host", "schemes"} {
		if value, present := document[key]; present {
			t.Errorf("%q = %v, want the key absent", key, value)
		}
	}
	if document["basePath"] != "/api" {
		t.Errorf("basePath = %v, want /api", document["basePath"])
	}
}
